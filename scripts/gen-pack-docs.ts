#!/usr/bin/env tsx
// scripts/gen-pack-docs.ts: `pnpm docs:packs`.
//
// Loads the bundled packs with the real loader (temporary home, in-memory
// secret store, no secrets set, no network) and writes docs/packs.md: every
// pack with its keys, permissions and tools. Packs that are off by default are
// switched on in the temporary home so their tools are listed too.
//
//   pnpm docs:packs            write docs/packs.md
//   pnpm docs:packs --check    exit 1 when docs/packs.md is out of date
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PackLoader, type PackStatus } from "../src/core/packs/loader.js";
import { createSecretStore } from "../src/core/secrets/index.js";
import { ToolRegistry } from "../src/core/tools/registry.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "docs", "packs.md");
const silent = { debug() {}, info() {}, warn() {}, error() {} };

/** The first sentence of a description, on one line, with table pipes escaped. */
function short(text: string): string {
  const one = text.replace(/\s+/g, " ").trim();
  const end = one.search(/\.(\s|$)/);
  const sentence = end >= 0 ? one.slice(0, end + 1) : one;
  return sentence.replace(/\|/g, "\\|");
}

function list(items: readonly string[]): string {
  return items.length ? items.map((i) => `\`${i}\``).join(", ") : "none";
}

function permissionLines(p: PackStatus["permissions"]): string[] {
  if (!p) return [];
  const lines: string[] = [];
  if (p.network?.length) lines.push(`- Network: ${list(p.network)}`);
  if (p.localNetwork?.length) lines.push(`- Local network: ${list(p.localNetwork.map(String))}`);
  if (p.spawn?.length) lines.push(`- Runs programs: ${list(p.spawn)}`);
  if (p.library && p.library !== "none") lines.push(`- Artifact library: ${p.library}`);
  if (p.llm) lines.push("- Calls the configured chat model");
  if (p.tools?.length) lines.push(`- Calls other tools: ${list(p.tools)}`);
  return lines;
}

async function render(): Promise<string> {
  const home = mkdtempSync(join(tmpdir(), "plughive-docs-"));
  const registry = new ToolRegistry();
  const store = createSecretStore({ home, env: {}, backend: "memory" });
  const loader = new PackLoader({
    home,
    registry,
    host: { store, logger: silent },
    userDir: join(home, "packs"),
  });
  try {
    await loader.loadAll();
    const offByDefault = (await loader.listPacks()).filter((p) => !p.enabled).map((p) => p.id);
    for (const id of offByDefault) await loader.enable(id);
    await loader.settled();
    const packs = (await loader.listPacks()).sort((a, b) => a.id.localeCompare(b.id));
    const tools = new Map(registry.list().map((t) => [t.name, t]));

    const out: string[] = [
      "# Bundled packs",
      "",
      "<!-- Generated by scripts/gen-pack-docs.ts. Run `pnpm docs:packs` after changing a pack. -->",
      "",
      "Each pack below ships with plughive. A pack that needs a key loads without",
      "one; its tools return a missing-key error until you save the key in the",
      "dashboard. The core tools (search_tools, list_artifacts, ...) are described",
      "in [protocol.md](protocol.md).",
      "",
      "| Pack | Tools | Keys | On by default |",
      "| --- | --- | --- | --- |",
    ];
    for (const p of packs) {
      const keys = p.secrets.map((s) => (s.required ? s.name : `${s.name} (optional)`));
      out.push(
        `| [${p.id}](#${p.id}) | ${p.tools.length} | ${keys.length ? keys.join(", ") : "none"} | ${offByDefault.includes(p.id) ? "no" : "yes"} |`,
      );
    }
    for (const p of packs) {
      out.push("", `## ${p.id}`, "");
      if (p.name && p.name !== p.id) out.push(`**${p.name}**, version ${p.version}.`, "");
      if (p.description) out.push(p.description.replace(/\s+/g, " ").trim(), "");
      if (offByDefault.includes(p.id))
        out.push("Off by default. Switch it on in the dashboard under Packs.", "");
      if (p.secrets.length) {
        out.push("Keys:", "");
        for (const s of p.secrets) {
          const where = s.helpUrl ? ` Get one at ${s.helpUrl}` : "";
          out.push(
            `- \`${s.name}\`${s.required ? "" : " (optional)"}: ${s.label ?? s.name}.${where}`,
          );
        }
        out.push("");
      }
      const perms = permissionLines(p.permissions);
      if (perms.length) out.push("Permissions:", "", ...perms, "");
      if (p.workflows.length) out.push(`Workflows: ${list(p.workflows)}`, "");
      if (p.mounts.length)
        out.push(`Mounted servers (each off until switched on): ${list(p.mounts)}`, "");
      if (p.tools.length) {
        out.push("| Tool | What it does |", "| --- | --- |");
        for (const name of [...p.tools].sort()) {
          out.push(`| \`${name}\` | ${short(tools.get(name)?.description ?? "")} |`);
        }
      } else if (p.state !== "loaded") {
        out.push(`Not loaded here: ${p.state}${p.error ? ` (${p.error})` : ""}.`);
      }
    }
    return `${out
      .join("\n")
      .replace(/\n{3,}/g, "\n\n")
      .trimEnd()}\n`;
  } finally {
    await loader.close();
    rmSync(home, { recursive: true, force: true });
  }
}

const text = await render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== text) {
    console.error("docs/packs.md is out of date. Run: pnpm docs:packs");
    process.exitCode = 1;
  } else {
    console.log("docs/packs.md is up to date.");
  }
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target.slice(root.length + 1)}`);
}
